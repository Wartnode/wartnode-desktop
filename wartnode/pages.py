def build_settings(self):
    page=self.page('Settings','Preferences for this desktop and profile.')
    area=QHBoxLayout();page.addLayout(area,1)
    self.settings_categories=QListWidget();self.settings_categories.setAccessibleName('Settings category')
    self.settings_categories.setMaximumWidth(145)
    self.settings_content=QStackedWidget()
    area.addWidget(self.settings_categories);area.addWidget(self.settings_content,1)
    self.preference_controls={}
    def category(title):
        self.settings_categories.addItem(title)
        widget=QWidget();body=QVBoxLayout(widget);body.setContentsMargins(18,0,0,0)
        body.addWidget(label(title,'section'));self.settings_content.addWidget(widget)
        return body
    def choice(body,title,key,values):
        control=QComboBox();control.setAccessibleName(title)
        for caption,value in values:control.addItem(caption,value)
        control.setCurrentIndex(control.findData(self.preferences[key]))
        form=QFormLayout();form.addRow(title,control);body.addLayout(form)
        self.preference_controls[key]=control
        control.currentIndexChanged.connect(lambda _:self.set_preference(key,control.currentData()))
        return control
    def check(body,title,key):
        control=QCheckBox(title);control.setChecked(self.preferences[key]);body.addWidget(control)
        self.preference_controls[key]=control
        control.toggled.connect(lambda checked:self.set_preference(key,checked))
        return control
    general=category('General')
    startup=check(general,'Launch at Windows startup','launch_at_startup')
    startup.setEnabled(bool(self.installed_root))
    startup.setToolTip('Open the desktop after sign-in. The node and miner start only when you choose.' if self.installed_root else 'Install Wartnode-Desktop to enable Windows startup.')
    check(general,'Close to system tray','close_to_tray')
    choice(general,'Start page','start_page',[(name,name) for name in settings.PAGES])
    choice(general,'Appearance','appearance',[('Dark','dark'),('System','system')])
    general.addWidget(label('The profile locks when the window closes. If the system tray is unavailable, closing exits the application.',muted=True));general.addStretch()
    security=category('Security')
