    check(security,'Hide balances','hide_balances')
    security.addWidget(button('Change profile password…',self.change_profile_password))
    security.addWidget(label('One password protects every address in this profile. Windows lock and explicit locking always lock the profile.',muted=True))
    security.addWidget(button('Back up profile…',self.backup_wallet))
    security.addWidget(button('Restore backup…',self.restore_wallet))
